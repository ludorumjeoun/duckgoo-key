    #[test]
    fn spotlight_parser_preserves_non_utf8_file_names() {
        let mut input = b"/Users/duck/".to_vec();
        input.push(0xff);
        input.extend_from_slice(b".txt\0");
        let expected = PathBuf::from(std::ffi::OsString::from_vec(
            b"/Users/duck/\xff.txt".to_vec(),
        ));

        let paths = read_nul_separated_paths(io::Cursor::new(input), 1).unwrap();

        assert_eq!(paths, vec![expected]);
    }

