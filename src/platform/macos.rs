pub fn available_input_sources() -> Result<Vec<InputSource>> {
    let input_sources = selectable_keyboard_input_sources()?;
    let mut values = Vec::with_capacity(input_sources.len() as usize);

    for input_source in input_sources.get_all_values() {
        let identifier = required_string_property(
            input_source,
            unsafe { kTISPropertyInputSourceID },
            INPUT_SOURCE_IDENTIFIER_PROPERTY,
        )?;
        let localized_name = optional_string_property(
            input_source,
            unsafe { kTISPropertyLocalizedName },
            LOCALIZED_NAME_PROPERTY,
        )?
        .filter(|name| !name.trim().is_empty())
        .unwrap_or_else(|| identifier.clone());
        values.push(InputSource {
            identifier,
            localized_name,
        });
    }

    Ok(normalize_input_sources(values))
}

pub fn current_input_source_identifier() -> Result<String> {
    let input_source = unsafe { TISCopyCurrentKeyboardInputSource() };
    if input_source.is_null() {
        return Err(PlatformError::CurrentInputSourceUnavailable);
    }

    // `TISCopy…` follows the Create Rule, so this owner must release the source.
    let _input_source_owner = unsafe { CFType::wrap_under_create_rule(input_source) };
    required_string_property(
        input_source,
        unsafe { kTISPropertyInputSourceID },
        INPUT_SOURCE_IDENTIFIER_PROPERTY,
    )
}

pub fn select_input_source(identifier: &str) -> Result<()> {
    let input_sources = selectable_keyboard_input_sources()?;
    for input_source in input_sources.get_all_values() {
        let candidate_identifier = required_string_property(
            input_source,
            unsafe { kTISPropertyInputSourceID },
            INPUT_SOURCE_IDENTIFIER_PROPERTY,
        )?;
        if candidate_identifier != identifier {
            continue;
        }

        let status = unsafe { TISSelectInputSource(input_source) };
        return if status == NO_ERR {
            Ok(())
        } else {
            Err(PlatformError::InputSourceSelectionFailed {
                identifier: identifier.to_owned(),
                status,
            })
        };
    }

    Err(PlatformError::InputSourceUnavailable {
        identifier: identifier.to_owned(),
    })
}

fn selectable_keyboard_input_sources() -> Result<CFArray> {
    let properties = unsafe {
        // Framework constants follow the Get Rule. The wrappers retain them while the
        // dictionary is assembled, and the dictionary then retains its keys and values.
        let category_key = CFString::wrap_under_get_rule(kTISPropertyInputSourceCategory);
        let enabled_key = CFString::wrap_under_get_rule(kTISPropertyInputSourceIsEnabled);
        let select_capable_key =
            CFString::wrap_under_get_rule(kTISPropertyInputSourceIsSelectCapable);
        let keyboard_category =
            CFString::wrap_under_get_rule(kTISCategoryKeyboardInputSource).into_CFType();
        let true_value = CFBoolean::true_value().into_CFType();

        CFDictionary::from_CFType_pairs(&[
            (category_key, keyboard_category),
            (enabled_key, true_value.clone()),
            (select_capable_key, true_value),
        ])
    };

    let input_sources =
        unsafe { TISCreateInputSourceList(properties.as_concrete_TypeRef(), false as Boolean) };
    if input_sources.is_null() {
        Err(PlatformError::InputSourceListUnavailable)
    } else {
        // `TISCreate…` follows the Create Rule; CFArray releases this snapshot on drop.
        Ok(unsafe { CFArray::wrap_under_create_rule(input_sources) })
    }
}

fn required_string_property(
    input_source: TISInputSourceRef,
    property_key: CFStringRef,
    property: &'static str,
) -> Result<String> {
    match optional_string_property(input_source, property_key, property)? {
        Some(value) if !value.is_empty() => Ok(value),
        Some(_) => Err(PlatformError::InputSourcePropertyEmpty { property }),
        None => Err(PlatformError::InputSourcePropertyMissing { property }),
    }
}

fn optional_string_property(
    input_source: TISInputSourceRef,
    property_key: CFStringRef,
    property: &'static str,
) -> Result<Option<String>> {
    let value = unsafe { TISGetInputSourceProperty(input_source, property_key) };
    if value.is_null() {
        return Ok(None);
    }

    // TIS properties follow the Get Rule, so retain the borrowed value before wrapping it.
    let value = unsafe { CFType::wrap_under_get_rule(value) };
    value
        .downcast::<CFString>()
        .map(|value| Some(value.to_string()))
        .ok_or(PlatformError::InputSourcePropertyTypeMismatch { property })
}

fn normalize_input_sources(input_sources: Vec<InputSource>) -> Vec<InputSource> {
    let mut by_identifier = BTreeMap::<String, InputSource>::new();
    for input_source in input_sources {
        by_identifier
            .entry(input_source.identifier.clone())
            .and_modify(|existing| {
                if localized_name_order(&input_source, existing).is_lt() {
                    existing.localized_name = input_source.localized_name.clone();
                }
            })
            .or_insert(input_source);
    }

    let mut input_sources = by_identifier.into_values().collect::<Vec<_>>();
    input_sources.sort_by(localized_name_order);
    input_sources
}

fn localized_name_order(left: &InputSource, right: &InputSource) -> CmpOrdering {
    left.localized_name
        .to_lowercase()
        .cmp(&right.localized_name.to_lowercase())
        .then_with(|| left.localized_name.cmp(&right.localized_name))
        .then_with(|| left.identifier.cmp(&right.identifier))
}

#[cfg(test)]
fn discover_in_roots(roots: &[PathBuf]) -> Vec<CatalogItem> {
    catalog_items_from_application_paths(discover_application_paths_in_roots(roots))
}

fn discover_application_paths_in_roots(roots: &[PathBuf]) -> Vec<PathBuf> {
    let mut applications = Vec::new();
    let mut seen_paths = HashSet::new();

    for root in roots.iter().filter(|root| root.is_dir()) {
        let mut entries = WalkDir::new(root).follow_links(false).into_iter();
        while let Some(entry) = entries.next() {
            let entry = match entry {
                Ok(entry) => entry,
                Err(error) => {
                    tracing::warn!(
                        root = %root.display(),
                        error = %error,
                        "Could not inspect part of an application directory"
                    );
                    continue;
                }
            };
            let path = entry.path();
            if !is_application_bundle(path) {
                continue;
            }

            if entry.file_type().is_dir() {
                entries.skip_current_dir();
            }
            if !path.is_dir() || !seen_paths.insert(path.to_owned()) {
                continue;
            }

            applications.push(path.to_owned());
        }
    }

    applications
}

fn catalog_items_from_application_paths(
    paths: impl IntoIterator<Item = PathBuf>,
) -> Vec<CatalogItem> {
    let mut applications = Vec::new();
    let mut seen_paths = HashSet::new();

    for path in paths {
        if !path.is_dir() || !is_application_bundle(&path) {
            continue;
        }
        let normalized_path = fs::canonicalize(&path).unwrap_or_else(|_| path.clone());
        if seen_paths.insert(normalized_path) {
            applications.push(catalog_item_from_bundle(&path));
        }
    }

    applications.sort_by(|left, right| {
        left.title
            .to_lowercase()
            .cmp(&right.title.to_lowercase())
            .then_with(|| left.id.cmp(&right.id))
    });
    applications
}

fn merge_application_catalog(
    direct_paths: Vec<PathBuf>,
    spotlight_paths: Option<Vec<PathBuf>>,
) -> Vec<CatalogItem> {
    catalog_items_from_application_paths(
        direct_paths
            .into_iter()
            .chain(spotlight_paths.into_iter().flatten()),
    )
}

fn is_application_bundle(path: &Path) -> bool {
    path.extension()
        .and_then(|extension| extension.to_str())
        .is_some_and(|extension| extension.eq_ignore_ascii_case("app"))
}

fn is_spotlight_launchable_application(path: &Path) -> bool {
    if !path.is_dir() || !is_application_bundle(path) || is_nested_application_bundle(path) {
        return false;
    }

    let Some(dictionary) = application_info_dictionary(path) else {
        return false;
    };
    if dictionary
        .get("LSBackgroundOnly")
        .and_then(Value::as_boolean)
        .unwrap_or(false)
    {
        return false;
    }

    dictionary
        .get("CFBundlePackageType")
        .and_then(Value::as_string)
        .is_none_or(|package_type| package_type.eq_ignore_ascii_case("APPL"))
}

fn is_nested_application_bundle(path: &Path) -> bool {
    path.ancestors().skip(1).any(is_application_bundle)
}

fn catalog_item_from_bundle(bundle_path: &Path) -> CatalogItem {
    let fallback_title = bundle_path
        .file_stem()
        .and_then(|name| name.to_str())
        .filter(|name| !name.trim().is_empty())
        .unwrap_or("Application")
        .to_owned();
    let dictionary = application_info_dictionary(bundle_path);

    let display_name = dictionary
        .as_ref()
        .and_then(|dictionary| nonempty_string(dictionary, "CFBundleDisplayName"))
        .or_else(|| {
            dictionary
                .as_ref()
                .and_then(|dictionary| nonempty_string(dictionary, "CFBundleName"))
        })
        .unwrap_or_else(|| fallback_title.clone());
    let icon_path = application_icon_path(bundle_path, dictionary.as_ref());

    let mut item = CatalogItem::application(bundle_path, display_name);
    item.icon_path = icon_path;
    if let Some(dictionary) = dictionary {
        for key in ["CFBundleName", "CFBundleIdentifier"] {
            if let Some(keyword) = nonempty_string(&dictionary, key)
                && !item
                    .keywords
                    .iter()
                    .any(|existing| existing.eq_ignore_ascii_case(&keyword))
                && !item.title.eq_ignore_ascii_case(&keyword)
            {
                item.keywords.push(keyword);
            }
        }
    }
    item
}

fn application_info_dictionary(bundle_path: &Path) -> Option<Dictionary> {
    let info_path = bundle_path.join("Contents/Info.plist");
    match Value::from_file(&info_path) {
        Ok(Value::Dictionary(dictionary)) => Some(dictionary),
        Ok(_) => {
            tracing::debug!(
                path = %info_path.display(),
                "Application Info.plist was not a dictionary"
            );
            None
        }
        Err(error) => {
            tracing::debug!(
                path = %info_path.display(),
                error = %error,
                "Application Info.plist could not be read"
            );
            None
        }
    }
}

fn application_icon_path(bundle_path: &Path, dictionary: Option<&Dictionary>) -> Option<PathBuf> {
    let resources = bundle_path.join("Contents/Resources");
    if !fs::symlink_metadata(&resources).is_ok_and(|metadata| metadata.file_type().is_dir()) {
        return None;
    }
    let canonical_resources = fs::canonicalize(&resources).ok()?;

    if let Some(dictionary) = dictionary {
        for candidate in icon_file_candidates(dictionary) {
            if let Some(path) = resolve_icon_candidate(&resources, &canonical_resources, candidate)
            {
                return Some(path);
            }
        }
    }

    fallback_icon_path(&resources)
}

fn icon_file_candidates(dictionary: &Dictionary) -> Vec<&str> {
    let mut candidates = Vec::new();
    append_icon_file_value(dictionary.get("CFBundleIconFile"), &mut candidates);

    let primary_icon = dictionary
        .get("CFBundleIcons")
        .and_then(Value::as_dictionary)
        .and_then(|icons| icons.get("CFBundlePrimaryIcon"))
        .and_then(Value::as_dictionary);
    if let Some(primary_icon) = primary_icon {
        append_icon_file_value(primary_icon.get("CFBundleIconFiles"), &mut candidates);
    }

    append_icon_file_value(dictionary.get("CFBundleIconFiles"), &mut candidates);
    candidates
}

fn append_icon_file_value<'a>(value: Option<&'a Value>, candidates: &mut Vec<&'a str>) {
    let Some(value) = value else {
        return;
    };

    if let Some(candidate) = value.as_string() {
        candidates.push(candidate);
    } else if let Some(values) = value.as_array() {
        candidates.extend(values.iter().filter_map(Value::as_string));
    }
}

fn resolve_icon_candidate(
    resources: &Path,
    canonical_resources: &Path,
    candidate: &str,
) -> Option<PathBuf> {
    let candidate = candidate.trim();
    if candidate.is_empty() {
        return None;
    }

    let relative = Path::new(candidate);
    if relative.is_absolute()
        || !relative
            .components()
            .all(|component| matches!(component, Component::Normal(_)))
    {
        return None;
    }

    let mut relative = relative.to_owned();
    if !relative
        .extension()
        .and_then(|extension| extension.to_str())
        .is_some_and(|extension| extension.eq_ignore_ascii_case("icns"))
    {
        let mut file_name = relative.file_name()?.to_os_string();
        file_name.push(".icns");
        relative.set_file_name(file_name);
    }

    let path = resources.join(relative);
    if !fs::symlink_metadata(&path).is_ok_and(|metadata| metadata.file_type().is_file()) {
        return None;
    }
    let canonical_path = fs::canonicalize(&path).ok()?;
    canonical_path
        .starts_with(canonical_resources)
        .then_some(path)
}

fn fallback_icon_path(resources: &Path) -> Option<PathBuf> {
    let mut icons = fs::read_dir(resources)
        .ok()?
        .filter_map(|entry| entry.ok())
        .filter_map(|entry| {
            let path = entry.path();
            let is_icns = path
                .extension()
                .and_then(|extension| extension.to_str())
                .is_some_and(|extension| extension.eq_ignore_ascii_case("icns"));
            (is_icns && entry.file_type().is_ok_and(|file_type| file_type.is_file()))
                .then_some(path)
        })
        .collect::<Vec<_>>();
    icons.sort();
    icons.into_iter().next()
}

fn nonempty_string(dictionary: &Dictionary, key: &str) -> Option<String> {
    dictionary
        .get(key)
        .and_then(Value::as_string)
        .map(str::trim)
        .filter(|value| !value.is_empty())
        .map(str::to_owned)
}

fn launch_agent_path() -> Option<PathBuf> {
    UserDirs::new().map(|directories| {
        directories
            .home_dir()
            .join("Library/LaunchAgents")
            .join(LAUNCH_AGENT_FILE_NAME)
    })
}

fn launch_at_login_enabled_at(path: &Path, executable: &Path) -> bool {
    let Ok(Value::Dictionary(dictionary)) = Value::from_file(path) else {
        return false;
    };

    let label_matches = dictionary
        .get("Label")
        .and_then(Value::as_string)
        .is_some_and(|label| label == LAUNCH_AGENT_LABEL);
    let run_at_load = dictionary
        .get("RunAtLoad")
        .and_then(Value::as_boolean)
        .unwrap_or(false);
    let executable_matches = dictionary
        .get("ProgramArguments")
        .and_then(Value::as_array)
        .and_then(|arguments| arguments.first())
        .and_then(Value::as_string)
        .is_some_and(|configured| Path::new(configured) == executable);
    let starts_hidden = dictionary
        .get("ProgramArguments")
        .and_then(Value::as_array)
        .and_then(|arguments| arguments.get(1))
        .and_then(Value::as_string)
        .is_some_and(|argument| argument == START_HIDDEN_ARGUMENT);

    label_matches && run_at_load && executable_matches && starts_hidden
}

fn write_launch_agent(path: &Path, executable: &Path) -> Result<()> {
    let parent = path
        .parent()
        .filter(|parent| !parent.as_os_str().is_empty())
        .ok_or_else(|| PlatformError::Io {
            operation: "locating the LaunchAgents directory",
            path: path.to_owned(),
            source: io::Error::new(io::ErrorKind::InvalidInput, "path has no parent"),
        })?;
    fs::create_dir_all(parent).map_err(|source| PlatformError::Io {
        operation: "creating the LaunchAgents directory",
        path: parent.to_owned(),
        source,
    })?;

    let mut dictionary = Dictionary::new();
    dictionary.insert(
        "Label".to_owned(),
        Value::String(LAUNCH_AGENT_LABEL.to_owned()),
    );
    dictionary.insert(
        "ProgramArguments".to_owned(),
        Value::Array(vec![
            Value::String(
                executable
                    .to_str()
                    .ok_or_else(|| PlatformError::InvalidExecutablePath(executable.to_owned()))?
                    .to_owned(),
            ),
            Value::String(START_HIDDEN_ARGUMENT.to_owned()),
        ]),
    );
    dictionary.insert("RunAtLoad".to_owned(), Value::Boolean(true));

    let mut encoded = Vec::new();
    Value::Dictionary(dictionary)
        .to_writer_xml(&mut encoded)
        .map_err(PlatformError::PlistSerialization)?;

    let (mut file, temp_path) = create_temporary_file(path)?;
    if let Err(source) = file.write_all(&encoded).and_then(|()| file.sync_all()) {
        let _ = fs::remove_file(&temp_path);
        return Err(PlatformError::Io {
            operation: "writing the launch-at-login property list",
            path: temp_path,
            source,
        });
    }
    drop(file);

    if let Err(source) = fs::rename(&temp_path, path) {
        let _ = fs::remove_file(&temp_path);
        return Err(PlatformError::Io {
            operation: "installing the launch-at-login property list",
            path: path.to_owned(),
            source,
        });
    }
    sync_directory(parent).map_err(|source| PlatformError::Io {
        operation: "synchronizing the LaunchAgents directory",
        path: parent.to_owned(),
        source,
    })
}

fn remove_launch_agent(path: &Path) -> Result<()> {
    match fs::remove_file(path) {
        Ok(()) => {}
        Err(source) if source.kind() == io::ErrorKind::NotFound => return Ok(()),
        Err(source) => {
            return Err(PlatformError::Io {
                operation: "removing the launch-at-login property list",
                path: path.to_owned(),
                source,
            });
        }
    }

    if let Some(parent) = path.parent() {
        sync_directory(parent).map_err(|source| PlatformError::Io {
            operation: "synchronizing the LaunchAgents directory",
            path: parent.to_owned(),
            source,
        })?;
    }
    Ok(())
}

fn create_temporary_file(target: &Path) -> Result<(File, PathBuf)> {
    let file_name = target.file_name().ok_or_else(|| PlatformError::Io {
        operation: "allocating a launch-at-login temporary file",
        path: target.to_owned(),
        source: io::Error::new(io::ErrorKind::InvalidInput, "path has no file name"),
    })?;

    for _ in 0..128 {
        let counter = TEMP_FILE_COUNTER.fetch_add(1, Ordering::Relaxed);
        let timestamp = SystemTime::now()
            .duration_since(UNIX_EPOCH)
            .map(|duration| duration.as_nanos())
            .unwrap_or(0);
        let mut name = file_name.to_os_string();
        name.push(format!(".tmp-{}-{timestamp}-{counter}", std::process::id()));
        let path = target.with_file_name(name);
        match OpenOptions::new().write(true).create_new(true).open(&path) {
            Ok(file) => return Ok((file, path)),
            Err(source) if source.kind() == io::ErrorKind::AlreadyExists => continue,
            Err(source) => {
                return Err(PlatformError::Io {
                    operation: "creating a launch-at-login temporary file",
                    path,
                    source,
                });
            }
        }
    }

    Err(PlatformError::Io {
        operation: "creating a launch-at-login temporary file",
        path: target.to_owned(),
        source: io::Error::new(
            io::ErrorKind::AlreadyExists,
            "could not allocate a unique temporary file",
        ),
    })
}

fn sync_directory(path: &Path) -> io::Result<()> {
    File::open(path)?.sync_all()
}

