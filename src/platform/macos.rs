pub fn execute_system_command(command: &SystemCommand) -> Result<()> {
    let spec = system_command_spec(command);
    let status = Command::new(spec.executable)
        .args(spec.arguments)
        .status()
        .map_err(|source| PlatformError::Io {
            operation: spec.operation,
            path: PathBuf::from(spec.executable),
            source,
        })?;
    if status.success() {
        Ok(())
    } else {
        Err(PlatformError::CommandFailed {
            executable: spec.executable,
            status: status.code(),
        })
    }
}

